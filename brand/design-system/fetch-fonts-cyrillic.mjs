#!/usr/bin/env node
/*
  Regenerate `fonts-cyrillic-embedded.css` — the JK brand fonts (Source Serif 4,
  IBM Plex Sans, IBM Plex Mono) as CYRILLIC-subset woff2 embedded as data URIs.

  Why this exists (companion to fetch-fonts.mjs): the firm's bilingual (Russian +
  English) proposals need the SAME brand faces to render Cyrillic. The main
  `fonts-embedded.css` is Latin-only to stay lean; this file adds the Cyrillic
  (and cyrillic-ext) subsets for the same families/weights, as separate
  @font-face blocks with a Cyrillic `unicode-range`. Include it ALONGSIDE
  `fonts-embedded.css` — the browser picks the right subset per glyph, so English
  keeps using the small Latin faces and only Russian pulls the Cyrillic ones.

  Only inline this where Cyrillic is actually needed (the Monthly Proposal
  generator's bilingual mode) — not in every tool — so Latin-only tools stay small.

  This is a MAINTENANCE script — re-run only to add a weight/subset or refresh the
  faces. The committed `fonts-cyrillic-embedded.css` is what tools actually use.

  Usage:  node brand/design-system/fetch-fonts-cyrillic.mjs
*/
import { writeFileSync } from 'node:fs';

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

// Same families/weights as fetch-fonts.mjs (DESIGN.md): Source Serif 4 400/600 + 400 italic;
// Plex Sans 400/500/600; Plex Mono 400/500/600.
const cssUrl = 'https://fonts.googleapis.com/css2?' +
  'family=Source+Serif+4:ital,opsz,wght@0,8..60,400;0,8..60,600;1,8..60,400' +
  '&family=IBM+Plex+Sans:wght@400;500;600' +
  '&family=IBM+Plex+Mono:wght@400;500;600' +
  '&display=swap';

const res = await fetch(cssUrl, { headers: { 'User-Agent': UA } });
if (!res.ok) { console.error('CSS fetch failed', res.status); process.exit(1); }
const css = await res.text();

const blocks = css.split('/*').slice(1).map(s => '/*' + s);
let out = '/* JK brand fonts — CYRILLIC subset, embedded woff2 (self-contained).\n' +
          '   Generated by fetch-fonts-cyrillic.mjs. Include ALONGSIDE fonts-embedded.css\n' +
          '   wherever Cyrillic must render (the bilingual RU/EN proposals). Latin text still\n' +
          '   uses the smaller Latin faces; only Cyrillic glyphs pull these. */\n';
let kept = 0;
for (const b of blocks) {
  const subset = (b.match(/\/\*\s*([a-z0-9-]+)\s*\*\//i) || [])[1] || '';
  if (subset !== 'cyrillic' && subset !== 'cyrillic-ext') continue;   // Cyrillic subsets only
  const woffUrl = (b.match(/url\((https:\/\/[^)]+\.woff2)\)/) || [])[1];
  if (!woffUrl) continue;
  const wr = await fetch(woffUrl, { headers: { 'User-Agent': UA } });
  if (!wr.ok) { console.error('woff2 fetch failed', wr.status, woffUrl); continue; }
  const b64 = Buffer.from(await wr.arrayBuffer()).toString('base64');
  out += b.replace(/\/\*[^*]*\*\/\s*/, '')
          .replace(/url\(https:\/\/[^)]+\.woff2\)\s*format\('woff2'\)/,
                   `url(data:font/woff2;base64,${b64}) format('woff2')`).trim() + '\n';
  kept++;
  const fam = (b.match(/font-family:\s*'([^']+)'/) || [])[1];
  const wt = (b.match(/font-weight:\s*(\d+)/) || [])[1];
  const st = (b.match(/font-style:\s*(\w+)/) || [])[1];
  console.error(`embedded ${fam} ${wt} ${st} (${subset})`);
}
writeFileSync(new URL('./fonts-cyrillic-embedded.css', import.meta.url), out);
console.error(`\nDone: ${kept} faces, ${(out.length/1024).toFixed(0)}KB → fonts-cyrillic-embedded.css`);
